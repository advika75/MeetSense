"""
Experiment runner for the evaluation/experimentation layer.

Runs, in dependency order:
  1. The four existing sample-level evaluation scripts (WER, DER,
     ROUGE, action-item P/R/F1) -- these read the production pipeline
     outputs (already generated by src/run_pipeline.py) and the
     manually-verified reference files.
  2. The three experimentation scripts added on top of them (model
     comparison, ablation study, error analysis) -- these reuse the
     JSON produced in step 1, so they must run after it.

This script does NOT re-run the production pipeline
(src/run_pipeline.py) -- it assumes the pipeline's outputs already
exist under outputs/transcripts/, outputs/nlp/, outputs/summaries/.

Every output JSON file this script is about to (re)write is backed up
to "<file>.bak" first if it already exists, so a run never silently
replaces prior results.
"""

import os
import shutil
import subprocess
import sys


STEPS = [
    (
        "Word Error Rate (WER) evaluation",
        "src/wer_evaluation.py",
        ["outputs/evaluations/wer_results.json"],
    ),
    (
        "Diarization Error Rate (DER) evaluation",
        "src/der_evaluation.py",
        ["outputs/evaluations/der_results.json"],
    ),
    (
        "ROUGE summary evaluation",
        "src/rouge_evaluation.py",
        ["outputs/evaluations/rouge_results.json"],
    ),
    (
        "Action item evaluation",
        "src/action_item_evaluation.py",
        ["outputs/evaluations/action_item_results.json"],
    ),
    (
        "Model / component comparison",
        "src/model_comparison.py",
        ["outputs/evaluations/model_comparison.json"],
    ),
    (
        "Ablation study",
        "src/ablation_study.py",
        ["outputs/evaluations/ablation_results.json"],
    ),
    (
        "Error analysis",
        "src/error_analysis.py",
        ["outputs/evaluations/error_analysis.json"],
    ),
]


def backup_existing_outputs(output_files):

    for path in output_files:

        if os.path.exists(path):

            backup_path = path + ".bak"

            shutil.copy2(path, backup_path)

            print(f"  Backed up existing {path} -> {backup_path}")


def main():

    print("=" * 70)
    print("EXPERIMENT RUNNER")
    print("=" * 70)

    print()
    print(
        "This assumes the production pipeline (src/run_pipeline.py) has "
        "already been run at least once -- it reads existing outputs, "
        "it does not regenerate them."
    )

    completed = []

    for step_number, (name, script, output_files) in enumerate(STEPS, start=1):

        print()
        print("=" * 70)
        print(f"STEP {step_number}/{len(STEPS)}: {name}")
        print("=" * 70)

        print()
        print("Checking for existing outputs to back up...")
        backup_existing_outputs(output_files)

        print()
        print(f"Running {script}...")
        print()

        result = subprocess.run(
            [sys.executable, script],
            check=False
        )

        if result.returncode != 0:

            print()
            print("=" * 70)
            print("EXPERIMENT RUNNER FAILED")
            print("=" * 70)

            print()
            print(f"Failed step: {name}")
            print(f"Script: {script}")
            print(f"Exit code: {result.returncode}")

            print()
            print("Completed before failure:")

            for done_name in completed:
                print(f"  - {done_name}")

            sys.exit(result.returncode)

        completed.append(name)

        print()
        print(f"✓ {name} completed successfully.")

        for path in output_files:
            print(f"  Wrote: {path}")

    print()
    print("=" * 70)
    print("ALL EXPERIMENTS COMPLETE")
    print("=" * 70)

    print()
    print("Generated / refreshed outputs:")

    for _, _, output_files in STEPS:
        for path in output_files:
            print(f"  {path}")

    print()
    print(
        "Any prior version of these files was preserved as "
        "'<file>.bak' before being overwritten."
    )


if __name__ == "__main__":
    main()
